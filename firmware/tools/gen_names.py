"""Write sim_names.yaml: a script that maps every LVGL widget id in ui.yaml to its name for the sim dump.

usage: python firmware/tools/gen_names.py   (run before compiling sim.yaml)
"""
import re
from pathlib import Path

FW = Path(__file__).resolve().parent.parent
WIDGETS = ("obj", "label", "button", "image", "slider", "tileview", "tile", "tabview", "dropdown", "roller",
           "switch", "checkbox", "textarea", "bar", "arc", "spinner", "buttonmatrix", "keyboard")


def widget_ids(text: str) -> list[str]:
    ids = []
    # "- label: { id: np_title, ... }" or "- label:\n    id: np_title"
    for m in re.finditer(r"-\s*(\w+):\s*(?:\{[^}]*?\bid:\s*(\w+)|\n\s+id:\s*(\w+))", text):
        if m.group(1) in WIDGETS:
            ids.append(m.group(2) or m.group(3))
    return list(dict.fromkeys(ids))


def main() -> None:
    ids = widget_ids((FW / "ui.yaml").read_text())
    fonts = re.findall(r"^  - id: (f\d+\w?)\n.*?size: (\d+)", (FW / "assets.yaml").read_text(), re.M | re.S)
    lines = ["# Generated by tools/gen_names.py; do not edit.", "script:", "  - id: sim_names", "    then:",
             "      - lambda: |-", "          auto &m = sim_name_map();", "          auto &f = sim_font_map();"]
    lines += [f'          m[umote_obj(id({i}))] = "{i}";' for i in ids]
    lines += ["          #ifdef USE_LVGL_FONT"]
    lines += [f"          f[id({fid})->get_lv_font()] = {size};" for fid, size in fonts]
    lines += ["          #endif"]
    (FW / "sim_names.yaml").write_text("\n".join(lines) + "\n")
    print(f"{len(ids)} widget ids, {len(fonts)} fonts")


if __name__ == "__main__":
    main()
