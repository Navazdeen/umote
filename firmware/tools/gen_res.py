"""Write ui_res.yaml: a script that hands every font and image in assets.yaml to ui::R (ui_lv.h).

usage: python firmware/tools/gen_res.py   (run after changing assets.yaml)
"""
import re
from pathlib import Path

FW = Path(__file__).resolve().parent.parent


def main() -> None:
    assets = (FW / "assets.yaml").read_text()
    fonts = re.findall(r"^  - id: (f\d+[a-z]?)$", assets, re.M)
    images = re.findall(r"^  - \{ id: ((?:ic|app)_\w+),", assets, re.M)
    lines = ["# Generated by tools/gen_res.py from assets.yaml; do not edit.", "script:", "  - id: ui_load_res",
             "    then:", "      - lambda: |-"]
    lines += [f"          ui::R.{f} = id({f})->get_lv_font();" for f in fonts]
    lines += [f'          ui::R.img["{i}"] = id({i})->get_lv_image_dsc();' for i in images]
    (FW / "ui_res.yaml").write_text("\n".join(lines) + "\n")
    print(f"{len(fonts)} fonts, {len(images)} images")


if __name__ == "__main__":
    main()
